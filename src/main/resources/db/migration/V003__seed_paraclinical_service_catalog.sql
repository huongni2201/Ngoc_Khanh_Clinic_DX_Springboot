-- Seed clinic departments, rooms and the paraclinical (cận lâm sàng) service catalog with prices.
-- Sources: the clinic's department list, room list and service list export (HIS ids 58526-58979).
-- Services whose name starts with 'BHYT' (health-insurance price list) are intentionally NOT imported.
--
-- Conventions:
--   * departments.code = upper-case ASCII slug of the name without the 'Khoa ' prefix.
--     department_type: CLINICAL for treating departments, DIAGNOSTIC for imaging/laboratory,
--     ADMINISTRATIVE for 'Hành chính'.
--   * rooms.code = ASCII slug of the room name plus its room number when it has one (P503); the second
--     'Khám SK' room gets the suffix _2. room_type: EXAMINATION (clinic rooms and reception desks),
--     PARACLINICAL (imaging/functional/lab rooms), SUPPORT (pharmacy, specimen drop-off).
--   * The consultation fees in the room list have no column in public.rooms and are NOT seeded here.
--   * services.code = 'CLS_' + source id, so each row stays traceable to the export.
--   * Every paraclinical service is performed by Khoa Chẩn Đoán Hình Ảnh, which owns the laboratory,
--     X-ray, ultrasound, endoscopy, ECG and EEG rooms in the room list.
--   * Only departments that own at least one room or service are seeded; the other departments in the
--     clinic's list (Khoa Cấp Cứu, Khoa Nội Tim Mạch, Khoa Cơ - Xương - Khớp, Khoa Xét nghiệm, Khoa X quang) are omitted until they have rooms or services.
--   * service_type: group 1 LAB, 2 ULTRASOUND, 3 XRAY, 4 ECG; endoscopy (6) and functional tests (8)
--     use OTHER, the closest value allowed by ck_services_type.
--   * Rows the export marked inactive are inserted with active = false.
--   * Source group fixes: the four 'Nội soi ... gây mê/không gây mê' rows were filed under laboratory
--     and are typed OTHER; Fibroscan is typed OTHER; 'Dịch vụ khác' is typed OTHER.
--   * ON CONFLICT DO NOTHING keeps the migration safe on databases that already hold these rows.

