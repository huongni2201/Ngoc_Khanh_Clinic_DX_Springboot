package com.ngockhanh.clinic.healthexamination.application.usecase;

import com.ngockhanh.clinic.audit.application.port.out.AuditWriter;
import com.ngockhanh.clinic.healthexamination.application.command.CreateHealthExaminationAgreementCommand;
import com.ngockhanh.clinic.healthexamination.application.response.AgreementDetailResponse;
import com.ngockhanh.clinic.healthexamination.application.service.AgreementCodeGenerator;
import com.ngockhanh.clinic.healthexamination.application.service.AgreementSupport;
import com.ngockhanh.clinic.healthexamination.domain.aggregate.HealthExaminationAgreement;
import com.ngockhanh.clinic.healthexamination.domain.enums.OrganizationStatus;
import com.ngockhanh.clinic.healthexamination.domain.exception.DomainRuleViolation;
import com.ngockhanh.clinic.healthexamination.domain.repository.HealthExaminationAgreementRepository;
import com.ngockhanh.clinic.healthexamination.domain.repository.OrganizationRepository;
import com.ngockhanh.clinic.healthexamination.domain.valueobject.AggregateId;
import com.ngockhanh.clinic.shared.exception.ResourceNotFoundException;
import com.ngockhanh.clinic.shared.infrastructure.id.UuidV7Generator;
import java.util.Map;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Creates a draft health examination agreement for an active organization.
 *
 * <p>The agreement code is generated by the system, never supplied by the caller. The header, its
 * services, and the audit event are written in one transaction, so a failure of any part rolls back
 * all of it. Concurrent creates are serialised while the code is allocated; the database unique
 * constraint on the code remains the last safeguard.
 */
@Slf4j
@Service
@RequiredArgsConstructor
public class CreateHealthExaminationAgreementUseCase {
  private final OrganizationRepository organizations;
  private final HealthExaminationAgreementRepository agreements;
  private final AgreementSupport support;
  private final AgreementCodeGenerator codes;
  private final AuditWriter audit;

  /**
   * Creates an agreement with status {@code DRAFT} and row version 0.
   *
   * @param organizationId owning organization
   * @param command agreement configuration
   * @param actor authenticated account creating the agreement
   * @return the agreement as stored, including timestamps
   * @throws IllegalArgumentException when an argument or the configuration is invalid
   * @throws ResourceNotFoundException when the organization does not exist
   * @throws DomainRuleViolation when the organization is inactive or a service is not available
   */
  @Transactional
  public AgreementDetailResponse execute(
      UUID organizationId, CreateHealthExaminationAgreementCommand command, UUID actor) {
    if (organizationId == null
        || command == null
        || command.configuration() == null
        || actor == null)
      throw new IllegalArgumentException(
          "Organization ID, configuration, and creator are required");
    var organization =
        organizations
            .findById(AggregateId.of(organizationId))
            .orElseThrow(() -> new ResourceNotFoundException("Organization"));
    if (organization.status() != OrganizationStatus.ACTIVE)
      throw new DomainRuleViolation("Organization is not active");

    var agreementId = new AggregateId(UuidV7Generator.generate());
    var configuration = command.configuration();
    var agreement =
        HealthExaminationAgreement.createDraft(
            agreementId,
            organization.id(),
            codes.next(),
            configuration.agreementName(),
            configuration.validFrom(),
            configuration.validTo(),
            support.newLines(agreementId, configuration.services(), 1));
    agreements.insert(agreement, actor);
    var stored =
        agreements
            .findDetails(organizationId, agreementId.value(), false)
            .orElseThrow(
                () -> new IllegalStateException("Created agreement could not be read back"));
    var response = support.toResponse(stored);
    audit.record(
        actor,
        "CREATE_HEALTH_EXAMINATION_AGREEMENT",
        "HEALTH_EXAMINATION_AGREEMENT",
        agreementId.value(),
        null,
        Map.of(
            "organizationId", organizationId,
            "status", response.status(),
            "rowVersion", response.rowVersion(),
            "configuration", response.auditSummary()));
    log.info(
        "Health examination agreement creation pending commit: organizationId={}, agreementId={},"
            + " services={}",
        organizationId,
        agreementId.value(),
        response.services().size());
    return response;
  }
}
